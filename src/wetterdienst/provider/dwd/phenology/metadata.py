def _dataset(
    reporter: str,
    group: str,
    stem: str,
    plant: str,
    object_id: int,
    periods: tuple[str, ...],
    phases: tuple[int, ...],
) -> dict:
    """Build one dataset -- one plant, as published by one reporter group."""
    prefix, reporter_prose = _REPORTERS[reporter]
    german, english, botanical = _OBJECTS[object_id]
    subject = f"{german} ({english}, {botanical})" if botanical else f"{german} ({english})"
    return {
        "name": f"{prefix}_{plant}",
        # the path to the file, minus the period directory and the period-dependent suffix
        "name_original": f"{reporter}/{group}/{stem}",
        "grouped": True,
        "periods": list(periods),
        "date_required": False,
        "description": f"Phenological phases of {subject}, observed by the DWD {reporter_prose}.",
        "parameters": [
            {
                "name": _PHASES[phase][0],
                "name_original": str(phase),
                "unit": "dimensionless",
                "description": f"{_PHASES[phase][2].capitalize()} ({_PHASES[phase][1]}).",
            }
            for phase in phases
        ],
    }


