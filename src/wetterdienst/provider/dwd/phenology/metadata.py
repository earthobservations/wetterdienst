"""DWD phenology metadata.

The DWD phenological network records, for one plant at one station, the day of the year on which
a given developmental phase was reached -- first flowering, leaf unfolding, harvest. Observations
come from two reporter groups: the *Jahresmelder* (annual reporters), who submit their whole
season at the end of the year, and the *Sofortmelder* (immediate reporters), who report a smaller
set of phases within days of observing them.

The source publishes one semicolon-separated, latin-1 encoded text file per plant, per reporter
group and per period, under
https://opendata.dwd.de/climate_environment/CDC/observations_germany/phenology/. A row is
``Stations_id;Referenzjahr;Qualitaetsniveau;Objekt_id;Phase_id;Eintrittsdatum;Eintrittsdatum_QB;Jultag``.

That file layout is what the model follows: one **dataset per plant** (all of its phases arrive
in one file) and one **parameter per phenological phase**. A value is ``Jultag``, the day of the
year the phase was reached, dated to the 1st of January of ``Referenzjahr`` at the ``annual``
resolution; ``quality`` carries ``Qualitaetsniveau``. A parameter's ``name_original`` is the
numeric ``Phase_id``, which is the only name the data files themselves use for a phase.

The plant and phase tables below are transcribed from the descriptions DWD publishes beside the
data -- ``PH_Beschreibung_Pflanze.txt`` and ``PH_Beschreibung_Phase.txt`` in
https://opendata.dwd.de/climate_environment/CDC/help/, and the per-group
``PH_Beschreibung_Phasendefinition_*.txt`` for which phases each plant is observed for. Two
typos in DWD's English column are corrected ("unfoalding", "mil ripeness"), and phase 68
(``Knospenschwellen``) is named from the immediate reporters' phase definitions, which is the
only place DWD lists it. ``tests/provider/dwd/phenology/test_api.py`` checks the tables here
against those files.
"""

