"""Every parameter of 0.139.0 that is gone is refused with a replacement, or is a removal with its reason (GH-3168).

The migration note from 0.139.0 promises that a name which no longer exists is refused with the one to use. The list
of what 0.139.0 declared and the checkout does not is `gone_since_0_139_0.json`, generated by
`uv run poe renames:baseline` (see `baseline_0_139_0.py`), so that this test works offline.
"""

import re
from pathlib import Path

import pytest

from tests.metadata.baseline_0_139_0 import GONE, read_gone
from tests.test_api import ALL_METADATA
from wetterdienst.model.metadata import DatasetModel, _find, _renamed_hint

# (metadata declaration, "resolution/dataset", name) of a parameter that is gone with nothing to name instead
REMOVED: dict[tuple[str, str, str], str] = {
    # GH-2851: MOSMIX_L never sends them (the all-stations file carries the same 114 elements and none of these eight).
    # `rr1c` and its siblings are other elements, "consistent with significant weather", so the near spelling the
    # error offers is a guess for the caller to weigh, not a rename
    **{
        ("DwdMosmixMetadata", "hourly/large", name): "GH-2851: MOSMIX_L never sends the element"
        for name in (
            "cloud_base_convective",
            "precipitation_amount_last_1h",
            "precipitation_amount_last_3h",
            "precipitation_amount_last_6h",
            "precipitation_amount_last_12h",
            "precipitation_amount_last_24h",
            "radiation_global_last_3h",
            "radiation_sky_long_wave_last_3h",
        )
    },
    ("DwdObservationMetadata", "daily/temperature_soil", "temperature_soil_mean_1m"): (
        "GH-2700: DWD publishes no 100 cm column (`v_te100m`)"
    ),
    ("MeteoFranceObservationMetadata", "hourly/core", "wind_direction_gust_max"): (
        "GH-2836: DXY is the direction of the hour's highest 10-minute mean and of no gust, not served"
    ),
    # GH-3245: no station of the service answers for them (`stations.json?timeseries=CL`, `NIEDERSCHLAG` and
    # `NIEDERSCHLAGSINTENSITÄT` are each `[]`, 786 stations and 20 shortnames, 2026-10-21)
    **{
        ("WsvPegelMetadata", f"{resolution}/data", name): "GH-3245: no station of the service serves it"
        for resolution in ("1_minute", "5_minutes", "10_minutes", "15_minutes", "hourly")
        for name in ("chloride_concentration", "precipitation_amount", "precipitation_intensity")
    },
    # GH-3235: null in all 49,688 observations of 108 stations; the METAR's 24 h group is only in the raw message
    **{
        (
            "NwsObservationMetadata",
            "hourly/data",
            name,
        ): "GH-3235: the API field is null at every station, never answers"
        for name in ("temperature_air_max_2m_last_24h", "temperature_air_min_2m_last_24h")
    },
}

# the same, for a name the dataset still answers to because it is the source's own: the request selects the row and
# the values come back under the new name
SOURCE_NAMES: dict[tuple[str, str, str], str] = {
    ("EcccObservationMetadata", "hourly/data", "wind_direction"): "ECCC's own field name",
    ("MetOfficeObservationMetadata", "hourly/weather", "wind_direction"): "the Met Office's own field name",
    ("MetOfficeObservationMetadata", "hourly/weather", "wind_speed"): "the Met Office's own field name",
    ("MetnoFrostMetadata", "hourly/data", "wind_speed"): "Frost's own element name",
}

_DATASETS = {
    (metadata.name, f"{resolution.name}/{dataset.name}"): dataset
    for metadata in ALL_METADATA
    for resolution in metadata
    for dataset in resolution
}
_GONE = [
    (metadata_name, key, name)
    for metadata_name, datasets in read_gone().items()
    for key, names in datasets.items()
    for name in names
]


def _hint(metadata_name: str, key: str, name: str) -> str:
    """Give the hint the refusal of the name in its dataset carries, or nothing."""
    dataset = _DATASETS[metadata_name, key]
    return _renamed_hint(name, {parameter.name.lower() for parameter in dataset}, dataset)


def test_the_list_of_what_is_gone_is_the_one_the_release_and_the_checkout_make() -> None:
    """The file is a document of a release, not a list to be kept by hand."""
    assert GONE.name == "gone_since_0_139_0.json"
    assert len(_GONE) > 300
    # a dataset of the checkout, under the name it has now
    assert sorted({(metadata_name, key) for metadata_name, key, _ in _GONE} - _DATASETS.keys()) == []


@pytest.mark.parametrize(
    ("metadata_name", "key", "name"), _GONE, ids=[f"{metadata}/{key}/{name}" for metadata, key, name in _GONE]
)
def test_a_parameter_gone_since_0_139_0_is_refused_with_its_replacement_or_is_a_removal(
    metadata_name: str, key: str, name: str
) -> None:
    """A name 0.139.0 had is refused with a hint, unless it is listed as a removal or as a name of the source."""
    hint = _hint(metadata_name, key, name)
    entry = (metadata_name, key, name)
    dataset: DatasetModel = _DATASETS[metadata_name, key]
    if entry in SOURCE_NAMES:
        # not refused at all: it selects the parameter the source calls so
        assert _find(dataset.parameters, name) is not None
        assert hint == ""
    elif entry in REMOVED:
        assert _find(dataset.parameters, name) is None
        assert hint == "", f"{entry} has a hint now, so it is no removal: {hint}"
    else:
        assert hint, f"{entry} is refused without a replacement: rename it in renamed.py, or list it as removed"
        assert _find(dataset.parameters, name) is None


def test_the_removals_and_source_names_are_all_gone_and_listed_once() -> None:
    """An entry of either set that is not in the generated list is stale."""
    gone = set(_GONE)
    assert sorted(set(REMOVED) - gone) == []
    assert sorted(set(SOURCE_NAMES) - gone) == []
    assert set(REMOVED).isdisjoint(SOURCE_NAMES)


@pytest.mark.parametrize(
    ("old", "new"), [("groundwater_level_max", "stage_max"), ("groundwater_level_min", "stage_min")]
)
def test_the_river_level_of_the_environment_agency_is_refused_with_the_stage_name(
    old: str, new: str, caplog: pytest.LogCaptureFixture
) -> None:
    """The daily river level was `groundwater_level_max` and `_min`, and the refusal names the stage (GH-3168)."""
    from wetterdienst.model.metadata import parse_parameters  # noqa: PLC0415
    from wetterdienst.provider.ea.hydrology import EAHydrologyMetadata  # noqa: PLC0415

    assert parse_parameters(f"daily/data/{old}", EAHydrologyMetadata, on_unknown="warn") == []
    assert f"It was renamed to '{new}' in this dataset." in caplog.text


def test_the_migration_page_states_the_counts_of_this_list() -> None:
    """The 'Verified' section of `migrating.md` gives the numbers that this list and its answers make (GH-3321).

    It said 361 and 347 of the refusals when the list held 403 entries: a number written into prose does not follow
    the list it counts. The numbers are computed here, and the page is held to them. Every issue that a removal cites
    is named in the section as well, so a removal added to `REMOVED` without a word there fails too.
    """
    text = (Path(__file__).parents[2] / "docs" / "usage" / "migrating.md").read_text(encoding="utf8")
    verified = text.partition("\n## Verified\n")[2].partition("\n## ")[0]
    assert verified, "migrating.md has no 'Verified' section"
    words = " ".join(verified.split())
    others = len(REMOVED) + len(SOURCE_NAMES)
    assert f"{len(_GONE)} parameters that a dataset of 0.139.0 has are not in the current release" in words
    assert f"{len(_GONE) - others} of the refusals name a replacement" in words
    assert f"The other {others} are:" in words
    cited = {issue for reason in REMOVED.values() for issue in re.findall(r"GH-\d+", reason)}
    assert sorted(issue for issue in cited if issue not in verified) == []
