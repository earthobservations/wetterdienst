import { addVitePlugin, defineNuxtModule } from 'nuxt/kit'
import { SEARCH_LOCALES, searchIndexFor, searchLabelsFor, searchSources } from './build'

// The full-text index of the app's own pages (GH-3790), as modules of the bundle: `virtual:search-index/<locale>` is the
// index of one language, built from the sources when the app is built, and `virtual:search-index/loaders` is the table
// that loads one (`() => import(...)`), so that every index is a chunk of its own, which the browser asks for the first
// time the search is opened and not before. Nothing is written to the repository and nothing is generated by hand: a build makes
// every index from the files as they are. The development server builds an index when it is asked for and again where a catalog
// (`i18n/locales/*.json`, read from the disk each time) has changed; the long texts (`i18n/measurement`, `i18n/methods`), the glossary
// labels (`i18n/glossary`) and the lists of `utils/` (`search-sources.ts`, `measurement.ts`, `works.ts`) are modules of this process,
// loaded once, so an edit of those needs a restart of the development server (reloading them for each request would mean a loader of
// our own for a file that is edited rarely; a production build is not affected).
// The module also has `labels`, the language's labels of the parameters (the names of the glossary's entries). `build.ts` says what it is built from.
const PREFIX = 'virtual:search-index/'
const RESOLVED = `\0${PREFIX}`

export default defineNuxtModule({
  meta: { name: 'search-index' },
  setup() {
    addVitePlugin({
      name: 'wetterdienst:search-index',
      resolveId(id: string) {
        return id.startsWith(PREFIX) ? `\0${id}` : undefined
      },
      load(this: { addWatchFile: (file: string) => void }, id: string) {
        if (!id.startsWith(RESOLVED))
          return undefined
        const name = id.slice(RESOLVED.length)
        if (name === 'loaders') {
          const entries = SEARCH_LOCALES.map(locale => `  ${JSON.stringify(locale)}: () => import(${JSON.stringify(`${PREFIX}${locale}`)}),`)
          return `export default {\n${entries.join('\n')}\n}\n`
        }
        if (!SEARCH_LOCALES.includes(name))
          return undefined
        for (const file of searchSources(name))
          this.addWatchFile(file)
        // `JSON.parse` of a string, which the engine reads faster than the same as a literal of that size
        return `export default JSON.parse(${JSON.stringify(JSON.stringify(searchIndexFor(name)))})\nexport const labels = JSON.parse(${JSON.stringify(JSON.stringify(searchLabelsFor(name)))})\n`
      },
    })
  },
})
