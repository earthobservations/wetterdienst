/**
 * The names of DWD's pollen regions in the reader's language (GH-4508).
 *
 * DWD writes the states and the 27 regions of its pollen forecast in German. The panel shows them in the reader's language and keeps
 * DWD's own name as a tooltip and an accessible description on each chip, so a reader can match it with DWD's pages. Only the display
 * changes: what is matched, stored and asked for stays DWD's id and German name (`utils/uv-pollen.ts`).
 *
 * What is translated (the maintainer's rule): the 16 states, by each language's established exonym (a language that normally uses the
 * German name keeps it), and the few generic words of the part-regions (lowlands, uplands, islands and marshes, west, east, "and" ...).
 * The place names stay as DWD writes them (Mainfranken, Allgäu, Oberbayern, Bay. Wald, Harz, Rhein-Main, Hohenlohe, Oberschwaben,
 * Donauniederungen, Ostwestfalen). A name is a template of the language, with the words of its own table and the states in `{...}`;
 * where the grammar of the language needs a case or an article that a slot cannot give (the Polish and Czech genitive, the Italian
 * "della" and "del"), the template writes it out. Two names are written out because word by word they would read badly: the
 * Rhein.-Westfäl. Tiefland (an abbreviated adjective, which becomes the language's own: "Rhine-Westphalian lowlands") and "nördl. der
 * Donau" (the river a phrase names is the language's own word: "north of the Danube"; the name of the region Donauniederungen stays).
 * A locale without a table (de, de-hh, lb: the German-speaking ones) shows DWD's names as they are.
 *
 * Every table is complete by its type: a locale that leaves out a state, a region or a word does not type-check, and
 * `tests/unit/pollen-names.test.ts` holds that none of them is empty and every slot is filled.
 */

